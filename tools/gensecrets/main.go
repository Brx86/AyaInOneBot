// gensecrets 把 .env 转成 internal/config/embedded_gen.go（构建标签 secrets），
// 使密钥内嵌进二进制并随 garble -literals 混淆；服务器因此无需明文配置文件。
// 没有 .env 时静默退出（保留 embedded_default.go 的空 map）。
//
// 生成的文件含密钥，已被 .gitignore 排除，勿提交。
package main

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"ayainonebot/internal/config"
)

const outPath = "internal/config/embedded_gen.go"

func main() {
	values := config.ParseFile(".env")
	if len(values) == 0 {
		return
	}
	keys := make([]string, 0, len(values))
	for k := range values {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by tools/gensecrets from .env; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// 此文件含密钥，已被 .gitignore 排除，勿提交。\n\n")
	b.WriteString("//go:build secrets\n\n")
	b.WriteString("package config\n\n")
	b.WriteString("// embedded 构建时从 .env 内嵌的配置值。\n")
	b.WriteString("var embedded = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, values[k])
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gensecrets: 生成的代码无法格式化:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, src, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "gensecrets:", err)
		os.Exit(1)
	}
}
